def read(path):
    p=ROOT/path
    return json.loads(p.read_text()) if p.exists() else None

def check_run(path,count=None):
    obj=read(path)
    if not obj:return 'NOT TESTED'
    if not obj.get('summary',{}).get('eligible'):return 'FAIL'
    if count is not None and len(obj.get('episodes',[]))!=count:return 'FAIL'
    return 'PASS'

